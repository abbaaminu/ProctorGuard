import '../entities/student_roster.dart';

/// A failure the administrator should read verbatim.
///
/// [message] is always user-facing prose: the repository translates
/// PostgREST/Edge-Function/network failures into it so the page can put it
/// straight in a SnackBar instead of the raw server string.
class AdminAccountException implements Exception {
  const AdminAccountException(this.message);

  final String message;

  @override
  String toString() => 'AdminAccountException: $message';
}

/// Account management for an admin: create a staff/student login, list every
/// profile, and move somebody between roles.
///
/// Only an `admin` can use any of it. The write paths enforce that twice: the
/// server (`admin-create-user` checks the caller's role before touching the
/// service_role key) and the database (`profiles_admin_all` + the
/// `guard_user_role_change()` trigger, which only lets an admin or the
/// service_role rewrite `role`).
abstract class AdminUserRepository {
  /// The most rows one `{ students: [...] }` request may carry. Mirrors the
  /// Edge Function's `MAX_BULK_STUDENTS`: a page larger than this is refused
  /// wholesale, so the caller pages by this number rather than discovering the
  /// limit from a 400.
  static const int maxStudentPageSize = 50;

  /// Creates an auth account *and* its `profiles` row through the
  /// `admin-create-user` Edge Function.
  ///
  /// The account comes back already email-confirmed, so [password] is the
  /// temporary password to hand over at sign-in. Throws
  /// [AdminAccountException] when the caller is not an admin, when the email is
  /// taken, or when the request never reached the server.
  ///
  /// [faculty], [department] and [level] are optional academic labels: they are
  /// written to the profile row so `exams_select` can offer that account papers
  /// targeted at its cohort. A blank value is *not* sent at all, which reads as
  /// "not stated" — the same thing a blank exam column means.
  ///
  /// [matricNumber] and [staffId] are the optional identity numbers the
  /// institution already knows the person by — the student's matriculation
  /// number, the staff member's badge number. They are recorded beside the
  /// labels and read by nobody in the schema: no policy compares them, so an
  /// account created without one (an administrator who does not have the number
  /// to hand, or a caller that predates them) behaves exactly like every account
  /// that already existed.
  Future<ManagedAccount> createAccount({
    required String email,
    required String password,
    required String fullName,
    required UserRole role,
    String? faculty,
    String? department,
    String? level,
    String? matricNumber,
    String? staffId,
  });

  /// Creates one page of a roster import through the same Edge Function, with
  /// an `{ students: [...] }` body.
  ///
  /// Every row becomes a `role='student'` account with a password generated by
  /// the server, which travels back in the answer — that password is the only
  /// way the account can be used, so it must reach the administrator.
  ///
  /// A page is *not* all-or-nothing: rows that could not be created come back in
  /// [StudentRosterOutcome.failed] with the reason, next to the ones that were.
  /// Send at most [maxStudentPageSize] rows per call. Throws
  /// [AdminAccountException] when the whole request failed (not an admin, the
  /// function is missing, the network dropped) — never because one address was
  /// already taken.
  Future<StudentRosterOutcome> createStudentAccounts(
    List<NewStudentAccount> students,
  );


  /// Every profile row the caller may read — an admin reads all of them
  /// (`profiles_select_own_or_staff`), so this is the full roster.
  Future<List<ManagedAccount>> listAccounts();

  /// Moves an existing account to a different role.
  ///
  /// Throws [AdminAccountException] when the caller may not write that row, or
  /// when [userId] no longer exists.
  Future<void> updateRole({required String userId, required UserRole role});

  /// Replaces the account's password through the `admin-reset-password` Edge
  /// Function — the way an administrator hands somebody a fresh temporary
  /// password when the old one is lost (this deployment has no self-service
  /// reset mail).
  ///
  /// Admins may do this for any account, their own included: unlike a role
  /// change or a deletion, it cannot lock the caller out of anything. [password]
  /// is passed through untrimmed — its spaces are part of it. Throws
  /// [AdminAccountException] when the caller is not an admin, when the account
  /// no longer exists, or when the request never reached the server.
  Future<void> resetPassword({
    required String userId,
    required String password,
  });

  /// Permanently removes the Auth login and its profile through the
  /// `admin-delete-user` Edge Function. Related exams, attempts and incidents
  /// are removed by database cascades.
  Future<void> deleteAccount({required String userId});
}
